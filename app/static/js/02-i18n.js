    // Fetch a language's pack once, from the versioned URL the page gives 00-lang.js.
    const _packLoads = {};
    function loadLanguagePack(lang) {
      if (lang === 'en' || I18N[lang]) return Promise.resolve();
      if (_packLoads[lang]) return _packLoads[lang];
      const holder = document.querySelector('script[data-pack-' + lang + ']');
      const url = holder ? holder.getAttribute('data-pack-' + lang) : '/static/js/i18n/' + lang + '.js';
      _packLoads[lang] = new Promise((resolve, reject) => {
        const s = document.createElement('script');
        s.src = url;
        s.onload = () => {
          if (window.I18N_PACKS && window.I18N_PACKS[lang]) { I18N[lang] = window.I18N_PACKS[lang]; resolve(); }
          else { delete _packLoads[lang]; reject(new Error('language pack missing')); }
        };
        s.onerror = () => { delete _packLoads[lang]; reject(new Error('language pack failed to load')); };
        document.head.appendChild(s);
      });
      return _packLoads[lang];
    }

