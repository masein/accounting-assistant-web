    // language by reloading the current page's data.
    async function switchLanguage(lang) {
      if (!SUPPORTED_UI_LANGUAGES.includes(lang)) return;
      try { await loadLanguagePack(lang); } catch (_) { applyLanguage(lang); return; }   // applyLanguage says why
      applyLanguage(lang, true);
      fetch(API + '/auth/preferences', {
        method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ language: lang }),
      }).catch(() => { /* offline: this browser still remembers it */ });
      const page = (location.hash || '#dashboard').slice(1);
      if (typeof loadPageData === 'function' && typeof validPages !== 'undefined' && validPages.has(page)) loadPageData(page);
    }

    async function saveLanguagePreference() {
      const lang = (uiLanguageSelectEl && uiLanguageSelectEl.value) || 'en';
      if (!SUPPORTED_UI_LANGUAGES.includes(lang)) {
        showAlert(t('unsupportedLanguage'), true);
        return;
      }
      try {
        if (saveLanguageBtn) saveLanguageBtn.disabled = true;
        const res = await fetch(API + '/auth/preferences', {
          method: 'PATCH',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ language: lang }),
        });
        const data = await res.json().catch(() => ({}));
        if (!res.ok) {
          showAlert(data.detail || t('msgLanguageUpdateFailed'), true);
          return;
        }
        // Persist, then reload so every dynamically-rendered surface
        // (dashboard KPIs, alerts, report tables) re-fetches and re-renders
        // in the new language — applyLanguage alone only re-translates the
        // static [data-i18n] elements, leaving JS-built content stale.
        localStorage.setItem('aa_ui_language', lang);
        location.reload();
      } catch (err) {
        showAlert(t('msgConnectionError') + err.message, true);
      } finally {
        if (saveLanguageBtn) saveLanguageBtn.disabled = false;
      }
    }
